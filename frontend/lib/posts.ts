export function getAllPosts(): Post[] {
  return POSTS;
}

export function getPostBySlug(slug: string): Post | undefined {
  if (!slug) return undefined;
  const decodedSlug = decodeURIComponent(slug).trim().toLowerCase();
  return POSTS.find(
    (post) =>
      post.slug.toLowerCase() === decodedSlug ||
      post.id.toString() === decodedSlug,
  );
}

export function getRelatedPosts(
  currentId: number,
  category?: string,
  limit: number = 3,
): Post[] {
  const others = POSTS.filter((p) => p.id !== currentId);
  if (!category) return others.slice(0, limit);

  const sameCategory = others.filter((p) => p.category === category);
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }

  const remaining = others.filter((p) => p.category !== category);
  return [...sameCategory, ...remaining].slice(0, limit);
}

export function getAdjacentPosts(currentId: number): {
  prev?: Post;
  next?: Post;
} {
  const index = POSTS.findIndex((p) => p.id === currentId);
  if (index === -1) return {};

  return {
    prev: index > 0 ? POSTS[index - 1] : undefined,
    next: index < POSTS.length - 1 ? POSTS[index + 1] : undefined,
  };
}
