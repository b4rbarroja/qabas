export function getAllPosts(): Post[] {
  return POSTS;
}

export function getPostBySlug(idOrSlug: string): Post | undefined {
  if (!idOrSlug) return undefined;
  const decoded = decodeURIComponent(idOrSlug).trim().toLowerCase();
  return POSTS.find(
    (post) =>
      post.id.toLowerCase() === decoded ||
      post.title.toLowerCase() === decoded,
  );
}

export function getRelatedPosts(
  currentId: string,
  hashtag?: string,
  limit: number = 3,
): Post[] {
  const others = POSTS.filter((p) => p.id !== currentId);
  if (!hashtag) return others.slice(0, limit);

  const sameCategory = others.filter((p) => p.hashtags.includes(hashtag));
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }

  const remaining = others.filter((p) => !p.hashtags.includes(hashtag));
  return [...sameCategory, ...remaining].slice(0, limit);
}

export function getAdjacentPosts(currentId: string): {
  prev?: Post;
  next?: Post;
} {
  const index = POSTS.findIndex((p) => p.id === currentId);
  if (index === -1) return {};

  return {
    prev: index > 0 ? POSTS[index - 1] : undefined,
    next: index < POSTS.length - 1 ? POSTS[index + 1] : undefined,
  };
}

